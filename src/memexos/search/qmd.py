"""Optional search backend: qmd (https://github.com/tobi/qmd), local vector search with a reranker.

MemexOS keeps its own named qmd index ("memexos-<vault id>" unless configured),
so it never touches collections you use qmd for elsewhere. The index's YAML
file (collection path, mask, exclusions, embedding model, context) is generated
from [search.qmd] in the settings on every `memex reindex`; change the settings,
not the file.

Vectors made by different embedding models cannot be mixed. When the model
changes, the next reindex embeds everything again with the new one (`qmd embed
-f`), and search keeps to the full-text index until that has finished.
"""

from __future__ import annotations

import json
import os
import re
import time
from pathlib import Path

from memexos.util import run, which

SNIP_NOISE = re.compile(r"@@[^@]*@@|^\(\d+ before, \d+ after\)\s*")
# log.md is the operations log and index.md the table of contents: neither is knowledge, and the table of contents
# resembles every question a little
EXCLUDE = [".memex/**", "raw/assets/**", ".git/**", ".obsidian/**", "log.md", "index.md"]


def command(cfg) -> str | None:
    return which(cfg.get("search.qmd.command") or "qmd")


def index_name(cfg) -> str:
    from memexos.config import vault_id
    return cfg.get("search.qmd.index") or f"memexos-{vault_id(cfg.vault)}"


def collection(cfg) -> str:
    return cfg.get("search.qmd.collection") or "memex"


def config_file(cfg) -> Path:
    base = os.environ.get("QMD_CONFIG_DIR") or os.path.join(os.environ.get("XDG_CONFIG_HOME") or os.path.expanduser("~/.config"), "qmd")
    return Path(base) / f"{index_name(cfg)}.yml"


def db_file(cfg) -> Path:
    base = os.environ.get("XDG_CACHE_HOME") or os.path.expanduser("~/.cache")
    return Path(base) / "qmd" / f"{index_name(cfg)}.sqlite"


def marker(cfg) -> Path:
    """{"index", "embed_model", "embedded_at"}: which index was embedded, with which model, when (null while a
    re-embedding after a model change is under way)."""
    return cfg.paths.state / "qmd.json"


def _marker(cfg) -> dict:
    try:
        m = json.loads(marker(cfg).read_text())
        return m if isinstance(m, dict) and m.get("index") == index_name(cfg) else {}
    except (OSError, ValueError):
        return {}


def ready(cfg) -> bool:
    """Usable for search: installed, indexed, and embedded at least once with the current model (the first embedding
    downloads models and can take a long time; until it has finished, search keeps to the built-in index)."""
    if not (command(cfg) and config_file(cfg).exists() and db_file(cfg).exists()):
        return False
    return bool(_marker(cfg).get("embedded_at"))


PROXY_VARS = ("https_proxy", "http_proxy", "all_proxy")


def _env(cfg) -> dict:
    """qmd works offline except for its one-time model downloads (from Hugging Face). [search.qmd] proxy picks their
    route ("" = [fetch] proxy, else the environment's proxy variables; "direct" = none; or a proxy URL). Node only
    honours proxy variables with NODE_USE_ENV_PROXY=1, and a proxy with its own CA needs NODE_EXTRA_CA_CERTS."""
    env = dict(os.environ)
    want = (cfg.get("search.qmd.proxy") or cfg.get("fetch.proxy") or "").strip()
    if want == "direct":
        return {k: v for k, v in env.items() if k.lower() not in PROXY_VARS}
    if want:
        for k in ("HTTPS_PROXY", "HTTP_PROXY", "https_proxy", "http_proxy"):
            env[k] = want
    if any(k.lower() in PROXY_VARS for k in env):
        env.setdefault("NODE_USE_ENV_PROXY", "1")
        ca = cfg.get("fetch.proxy_cacert") or ""
        if ca and "NODE_EXTRA_CA_CERTS" not in env:
            env["NODE_EXTRA_CA_CERTS"] = os.path.expanduser(ca)
    return env


QWEN3_EMBED = "hf:Qwen/Qwen3-Embedding-0.6B-GGUF/Qwen3-Embedding-0.6B-Q8_0.gguf"
GENERATED = "# Generated by MemexOS from [search.qmd] in its settings on every `memex reindex`; edit those, not this file.\n"


def embed_model(cfg) -> str:
    """The embedding model the index should use; "" = qmd's default. [search.qmd] embed_model "auto" picks by the
    knowledge base's language: qmd's default model is weak on Chinese, where Qwen3-Embedding does much better."""
    v = (cfg.get("search.qmd.embed_model") or "").strip()
    if v == "auto":
        return QWEN3_EMBED if cfg.language == "zh" else ""
    return v


def index_config(cfg) -> str:
    lines = [GENERATED.rstrip()]
    model = embed_model(cfg)
    if model:
        lines += ["models:", f"  embed: {json.dumps(model)}"]
    ignore = list(dict.fromkeys(EXCLUDE + list(cfg.get("search.qmd.ignore") or [])))
    lines += ["collections:", f"  {collection(cfg)}:", f"    path: {json.dumps(str(cfg.vault))}", '    pattern: "**/*.md"',
              "    ignore:"] + [f"      - {json.dumps(x)}" for x in ignore]
    desc = cfg.get("search.qmd.context") or ""
    if desc:
        lines += ["    context:", f'      "": {json.dumps(desc, ensure_ascii=False)}']
    return "\n".join(lines) + "\n"


def ensure_index(cfg) -> str:
    """Write the named index's config from the settings. Returns "created", "updated" or "unchanged"."""
    f = config_file(cfg)
    want = index_config(cfg)
    old = f.read_text(encoding="utf-8") if f.exists() else None
    if old == want:
        return "unchanged"
    f.parent.mkdir(parents=True, exist_ok=True)
    from memexos.util import atomic_write
    atomic_write(f, want)
    return "created" if old is None else "updated"


def _save_marker(cfg, model: str, embedded: bool) -> None:
    marker(cfg).parent.mkdir(parents=True, exist_ok=True)
    marker(cfg).write_text(json.dumps({"index": index_name(cfg), "embed_model": model,
                                       "embedded_at": time.strftime("%Y-%m-%dT%H:%M:%S") if embedded else None}))


def update(cfg, embed: bool = True) -> dict:
    exe = command(cfg)
    if not exe:
        return {"ok": False, "why": "qmd not installed"}
    ensure_index(cfg)
    model = embed_model(cfg)
    m = _marker(cfg)
    # an index embedded before MemexOS recorded the model: take it as made with the current one
    changed = bool(m) and "embed_model" in m and m["embed_model"] != model
    out = run([exe, "--index", index_name(cfg), "update"], env=_env(cfg), timeout=3600)
    msg = out.stdout + out.stderr
    if embed and out.returncode == 0:
        if changed:                        # vectors of two models cannot be mixed: start over, search without them meanwhile
            _save_marker(cfg, model, embedded=False)
        e = run([exe, "--index", index_name(cfg), "embed"] + (["-f"] if changed else []), env=_env(cfg), timeout=3600 * 3)
        msg += e.stdout + e.stderr
        if e.returncode == 0:              # vectors exist: from now on search may use them
            _save_marker(cfg, model, embedded=True)
    return {"ok": out.returncode == 0, "summary": " ".join(re.findall(r"(Indexed:[^\n]*|Embedded [^\n]*)", msg))[:300],
            "why": "" if out.returncode == 0 else msg.strip()[-300:], **({"model_changed": model or "qmd default"} if changed else {})}


def query(cfg, mode: str, q: str, n: int, degraded: list) -> list[dict] | None:
    """mode: vsearch (vectors) | search (qmd's BM25) | query (expansion + rerank). Returns [{path, title, snippet}]."""
    exe = command(cfg)
    if not exe:
        return None
    try:
        r = run([exe, "--index", index_name(cfg), mode, q, "--json", "-n", str(n), "-c", collection(cfg)],
                env=_env(cfg), timeout=300)
    except Exception as e:  # noqa: BLE001
        degraded.append(f"qmd {mode} failed ({type(e).__name__})")
        return None
    if r.returncode != 0:
        errs = [l.strip() for l in r.stderr.splitlines() if re.search(r"Error|error:|CANTOPEN|denied|not permitted", l)]
        degraded.append(f"qmd {mode} unavailable ({(errs[-1] if errs else r.stderr.strip()[-100:]) or 'no output'})")
        return None
    try:
        items = json.loads(r.stdout or "[]")
    except ValueError:
        return []
    out = []
    for h in items:
        p = re.sub(r"^qmd://[^/]+/", "", h.get("file") or "").split("?", 1)[0].split(":", 1)[0]
        if p:
            out.append({"path": p, "title": h.get("title") or Path(p).stem, "snippet": SNIP_NOISE.sub("", h.get("snippet", "")).strip()})
    return out


def models(cfg, action: str = "check", deep: bool = False) -> dict:
    """The local models search needs: the embedding model (per [search.qmd] embed_model), the reranker and, with
    deep=True, qmd's query expansion model (only `--mode deep` uses it). action "check" returns {model: path or None};
    "pull" downloads what is missing (with a progress bar on a terminal) and never deletes or replaces a downloaded
    model, unlike `qmd pull`."""
    import importlib.resources as resources
    pkg = package_dir()
    if not pkg or not which("node"):
        return {"ok": False, "why": "qmd or node not found", "models": {}}
    want = [embed_model(cfg) or "embed", "rerank"] + (["generate"] if deep else [])
    script = resources.files("memexos.search").joinpath("qmd_models.mjs")
    import subprocess
    r = subprocess.run(["node", str(script), action, *want], env={**_env(cfg), "QMD_PKG": str(pkg)}, stdout=subprocess.PIPE,
                       stderr=None if action == "pull" else subprocess.PIPE, text=True, timeout=7200)
    try:
        found = json.loads((r.stdout or "").strip().splitlines()[-1])
    except (ValueError, IndexError):
        found = {}
    return {"ok": r.returncode == 0 and all(found.get(m) for m in want), "models": found,
            "why": "" if r.returncode == 0 else (r.stderr or "").strip()[-300:] if action != "pull" else "download failed"}


def models_dir() -> Path:
    return Path(os.environ.get("XDG_CACHE_HOME") or os.path.expanduser("~/.cache")) / "qmd" / "models"


def reranker_model() -> Path | None:
    """qmd's local reranker model, when it has already been downloaded (qmd fetches it on first use, which takes a while)."""
    d = models_dir()
    hits = sorted(d.glob("*rerank*.gguf")) if d.is_dir() else []
    return hits[0] if hits else None


def package_dir() -> Path | None:
    """Where qmd's JavaScript package is installed (to reuse its local reranker model)."""
    exe = which("qmd")
    if not exe:
        return None
    p = Path(os.path.realpath(exe))
    for d in [p.parent, *p.parents]:
        pj = d / "package.json"
        if pj.is_file():
            try:
                if json.loads(pj.read_text()).get("name", "").endswith("/qmd") or json.loads(pj.read_text()).get("name") == "qmd":
                    return d
            except ValueError:
                pass
    return None
